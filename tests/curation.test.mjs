import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
import {defaultSelection,prepareProjects,selectedProjects} from '../public/curation.mjs';
const picture={url:'/assets/bottle.jpg',width:1200,height:12000};
const all=defaultSelection.map((id,i)=>({id,title:id,category:i>9?'Editorial':'Packaging',published:true,demo:false,cover:picture,details:[picture],description:''})).reverse();
all.push({ ...all[0],id:'extra',category:'Brand identity'});
const snapshot=JSON.stringify(all);
assert.deepEqual(selectedProjects(all).map(p=>p.id),defaultSelection);
assert.equal(JSON.stringify(all),snapshot);
assert.equal(selectedProjects(all)[0].details[0].height,12000);
const prepared=prepareProjects(all);
assert.equal(prepared.length,13);assert.equal(prepared.filter(p=>p.featured).length,12);
prepared[0].featured=false;
assert.equal(selectedProjects(prepared).length,11); // Never refill a deliberate removal.
prepared.at(-1).featured=true;
assert.equal(selectedProjects(prepared).length,12);
assert.ok(selectedProjects(prepared).slice(-2).every(p=>p.category==='Editorial'));
prepared[1].published=false;assert.equal(selectedProjects(prepared).length,11);
prepared[2].demo=true;assert.equal(selectedProjects(prepared).length,10);
const reverse=prepareProjects(all).reverse();
assert.deepEqual(selectedProjects(reverse).slice(-2).map(p=>p.id),[defaultSelection[11],defaultSelection[10]]);
const code=ts.transpileModule(await readFile('lib/portfolio-validation.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText;
const {validateProjects}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const saved=validateProjects(prepareProjects(all));
assert.equal(saved.filter(p=>p.featured).length,12);assert.equal(saved.length,13);
assert.equal(saved[0].details[0].height,12000);
assert.throws(()=>validateProjects(saved.map(p=>({...p,featured:true}))),/12/);
assert.throws(()=>validateProjects([{...saved[0],featured:'true'}]),/精选设置/);
assert.equal(validateProjects(all)[0].featured,undefined);
console.log('PASS: initial 12 selections, retained works and long images, manual replacement, order, drafts, demos and server validation.');
